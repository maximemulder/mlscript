/** Check a body against a supplied contract, retaining local immutable-path refinements.
 *  Generated constraints are conjunctive: each reachable branch must satisfy the contract. */
def checkExpr(expr: Expr, expected: Type)(using ctx: TypeContext): SubClauses =
  val checker = BodyChecker(ctx)
  checker.check(expr, expected, CheckEnv())
  checker.outs

/** Local bindings, aliases, and refinements. Only immutable variable/projection paths are aliased. */
private case class CheckEnv(
  bindings: Map[TermVar, Type] = Map.empty,
  aliases: Map[TermVar, Expr] = Map.empty,
  paths: Map[Expr, Type] = Map.empty,
):
  /** Canonicalize a path without duplicating an evaluated computation. */
  def path(expr: Expr): Expr = expr match
    case EVar(v) => aliases.get(v).filter(_ != expr).fold(expr)(path)
    case EProj(e, f) => EProj(path(e), f)
    case ETupleProj(e, first) => ETupleProj(path(e), first)
    case EAscr(e, _) => path(e)
    case _ => expr

  /** Bind a value, sharing refinement information with its source when that source is a path. */
  def bind(v: TermVar, t: Type, source: Option[Expr] = None): CheckEnv =
    val origin = source.map(path).filter:
      case EVar(_) | EProj(_, _) | ETupleProj(_, _) => true
      case _ => false
    assert(origin.forall(e => e == EVar(v) || !e.freeVars(v)))
    copy(bindings = bindings.updated(v, t), aliases = origin match
      case Some(e) if e != EVar(v) => aliases.updated(v, e)
      case _ => aliases - v)

/** A checking invocation owns all its generated inference variables and constraints. */
private class BodyChecker(base: TypeContext):
  /** Constraints generated by evaluated expressions and checked branches. */
  var outs: SubClauses = SubClauses.empty

  /** Current context, including every generated obligation. */
  private def ctx: TypeContext = base.extendSub(outs)

  /** Require an inclusion rather than using an unverified candidate as evidence. */
  private def requireSubtype(a: Type, b: Type): Unit =
    outs = subtypeSeq(a, b, outs)(using base.sub)

  /** Resolve transparent aliases, without following cyclic bounds. */
  private def alias(t: Type, seen: Set[TypeVar] = Set.empty): Type = t match
    case TVar(v) if !seen(v) =>
      val lo = ctx.sub.getVarBound(v, Direction.Super)
      val hi = ctx.sub.getVarBound(v, Direction.Sub)
      if lo == hi then alias(hi, seen + v) else t
    case _ => t

  /** Expose one positive encoded recursive layer, proving the unfolding obligation. */
  private def layer(t: Type): Type = alias(t) match
    case u @ TUniv(v, TConstrained(TVar(w), Constraint(TVar(x), Direction.Super, f)))
      if v == w && v == x =>
      val exposed = f.substitute(v, u)
      requireSubtype(t, exposed)
      exposed
    case a => a

  /** Expose only the finite field depth inspected by a pattern. Unfolding is covariant;
   *  negative occurrences retain their original type and cannot justify stronger assumptions. */
  private def patternLayer(t: Type, pattern: Type): Type =
    if pattern == TTop then return t
    val fields = patternFields(pattern)
    /** Unfold covariant record fields selected by the pattern. */
    def expose(t: Type): Type = t match
      case TJointType(mode, a, b) => TJointType(mode, expose(a), expose(b))
      case TField(name, value) if fields.contains(name) =>
        TField(name, patternLayer(value, fields(name)))
      case _ => t
    expose(layer(t))

  /** Collect the nested field tests at this pattern depth. */
  private def patternFields(t: Type): Map[String, Type] = t match
    case TField(name, value) => Map(name -> value)
    case TJointType(_, a, b) =>
      patternFields(b).foldLeft(patternFields(a)):
        case (fields, (name, value)) => fields.updated(name,
          fields.get(name).fold(value)(TJointType(JointMode.Inter, _, value)))
    case TNeg(body) => patternFields(body)
    case _ => Map.empty

  /** Instantiate a function scheme, retaining its guards as obligations. */
  private def open(t: Type): Type = alias(t) match
    case u: TUniv =>
      val (vars, body) = u.getUnivComponents
      val (instance, decls) = instantiateUniv(vars, body, TypeVarKind.Flex)(using ctx.sub)
      outs = outs.concat(decls)
      open(instance)
    case TConstrained(body, guard) =>
      outs = subtypeConstraintSeq(guard, outs)(using base.sub)
      open(body)
    case t => t

  /** Check an expression, propagating expected arrows through lambdas and branches. */
  def check(expr: Expr, expected: Type, env: CheckEnv): Unit =
    (expr, alias(expected)) match
      case (ELam(param, body), TLam(input, output)) =>
        param match
          case Some(p) =>
            p.annotation.foreach(requireSubtype(input, _))
            check(body, output, env.bind(p.variable, input))
          case None =>
            requireSubtype(input, TClass(ClassVar("Unit")))
            check(body, output, env)
      case (EApp(ELam(Some(p), body), arg), _) =>
        val value = synth(arg, env)
        p.annotation.foreach(requireSubtype(value, _))
        check(body, expected, env.bind(p.variable, value, Some(arg)))
      case (m: EMatch, _) =>
        branches(m, env)((body, branch) => check(body, expected, branch))
      case (EAscr(body, annotation), _) =>
        check(body, annotation, env)
        requireSubtype(annotation, expected)
      case _ => requireSubtype(synth(expr, env), expected)

  /** Check each reachable branch under a refinement of its evaluated scrutinee. */
  private def branches(m: EMatch, env: CheckEnv)(visit: (Expr, CheckEnv) => Unit): Unit =
    if !hkmc2.ctml.config.config.arbitraryPatterns && !m.pattern.isPattern(using ctx) then
      throw TypeError(Some(s"Pattern ${m.pattern} is not a supported runtime pattern."))
    val input = patternLayer(synth(m.scrutinee, env), m.pattern)
    val yes = meet(input, m.pattern)(using ctx.sub)
    val no = meet(input, TNeg(m.pattern))(using ctx.sub)
    if m.else_.isEmpty then requireSubtype(input, m.pattern)
    /** Check a reachable branch without exporting its path assumptions. */
    def branch(body: Expr, refined: Type): Unit =
      if !checkSubtype(refined, TBot)(using ctx.sub) then
        visit(body, env.copy(paths = env.paths.updated(env.path(m.scrutinee), refined)))
    branch(m.then_, yes)
    m.else_.foreach(branch(_, no))

  /** Synthesize evaluated values; branch results are joined without exporting their histories. */
  private def synth(expr: Expr, env: CheckEnv): Type =
    (expr match
      case EVar(_) | EProj(_, _) | ETupleProj(_, _) => env.paths.get(env.path(expr))
      case _ => None) match
      case Some(t) => return t
      case _ =>
    expr match
      case EVar(v) => env.bindings.getOrElse(v, ctx.getVarType(v))
      case EUnit => TClass(ClassVar("Unit"))
      case EAscr(e, t) =>
        check(e, t, env)
        t
      case EApp(ELam(Some(p), body), arg) =>
        val t = synth(arg, env)
        p.annotation.foreach(requireSubtype(t, _))
        synth(body, env.bind(p.variable, t, Some(arg)))
      case EApp(fn, arg) =>
        open(synth(fn, env)) match
          case TLam(input, output) =>
            check(arg, input, env)
            output
          case fnType =>
            val input = synth(arg, env)
            val result = ctx.sub.declInferVar()
            outs = outs.concat(result.asSubClauses)
            requireSubtype(fnType, TLam(input, TVar(result.var_)))
            TVar(result.var_)
      case ETypeApp(e, args) =>
        open(instantiateExplicit(synth(e, env), args)(using ctx.sub))
      case EProj(e, name) =>
        val record = layer(synth(e, env))
        val result = ctx.sub.declInferVar()
        outs = outs.concat(result.asSubClauses)
        requireSubtype(record, TField(name, TVar(result.var_)))
        // The field's collected lower bound is a valid choice for this fresh existential.
        val value = ctx.sub.getVarBound(result.var_, Direction.Super)
        requireSubtype(TVar(result.var_), value)
        value
      case ETupleProj(e, first) =>
        val product = synth(e, env)
        val result = ctx.sub.declInferVar()
        outs = outs.concat(result.asSubClauses)
        val t = TVar(result.var_)
        requireSubtype(product, if first then TTuple(t, TTop) else TTuple(TTop, t))
        val value = ctx.sub.getVarBound(result.var_, Direction.Super)
        requireSubtype(t, value)
        value
      case ETuple(a, b) => TTuple(synth(a, env), synth(b, env))
      case ERecord(tag, fields) =>
        fields.foldLeft(TClass(tag): Type):
          case (t, (name, e)) => TJointType(JointMode.Inter, t, TField(name, synth(e, env)))
      case m: EMatch =>
        var result: Type = TBot
        branches(m, env): (body, branch) =>
          result = join(result, synth(body, branch))(using ctx.sub)
        result
      case _ =>
        val bindings = env.bindings.toList.map((v, t) => TermVarDecl(v, t))
        val (t, generated) = infer(expr)(using ctx.copy(terms = bindings ::: ctx.terms))
        outs = outs.concat(generated)
        t
